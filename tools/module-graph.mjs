// The site's JavaScript module graph, starting from js/app.js: every module
// it imports, directly or indirectly, in a stable order.
//
// Used two ways:
//   node tools/module-graph.mjs --write   rewrites the <link rel="modulepreload">
//                                         block in index.html, so the browser
//                                         fetches every module at once instead
//                                         of discovering them one import at a time
//   tests/deploy.test.js                  fails if that block is out of date
//
// No build step and no dependencies - static imports are read with a regex
// (the codebase has no dynamic imports of its own modules).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IMPORT = /(?:^|\n)\s*(?:import|export)\s[^;]*?from\s*["']([^"']+)["']|(?:^|\n)\s*import\s*["']([^"']+)["']/g;

export function moduleGraph(entry = "js/app.js") {
  const seen = new Set();
  const order = [];
  const visit = (rel) => {
    if (seen.has(rel)) return;
    seen.add(rel);
    const text = fs.readFileSync(path.join(ROOT, rel), "utf8");
    for (const m of text.matchAll(IMPORT)) {
      const spec = m[1] ?? m[2];
      if (!spec.startsWith(".")) continue;
      visit(path.posix.normalize(path.posix.join(path.posix.dirname(rel), spec)));
    }
    order.push(rel);
  };
  visit(entry);
  return order.filter((m) => m !== entry).sort();
}

export const START = "<!-- modulepreload:start (generated by tools/module-graph.mjs --write) -->";
export const END = "<!-- modulepreload:end -->";
export const preloadBlock = (modules) => [START, ...modules.map((m) => `<link rel="modulepreload" href="${m}" />`), END].join("\n");

if (process.argv.includes("--write")) {
  const file = path.join(ROOT, "index.html");
  const html = fs.readFileSync(file, "utf8");
  const nl = html.includes("\r\n") ? "\r\n" : "\n";
  const block = preloadBlock(moduleGraph()).replace(/\n/g, nl);
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
  const next = re.test(html) ? html.replace(re, block) : html.replace(`<script type="module" src="js/app.js"></script>`, `${block}${nl}<script type="module" src="js/app.js"></script>`);
  fs.writeFileSync(file, next);
  console.log(`index.html: ${moduleGraph().length} modules preloaded`);
}
